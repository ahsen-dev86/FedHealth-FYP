// Hook that reports whether the viewport is narrower than the mobile
// breakpoint (matches Tailwind's `md` breakpoint); used by the sidebar to
// switch between the desktop layout and the mobile drawer.
import * as React from "react"

const MOBILE_BREAKPOINT = 768

export function useIsMobile() {
  const [isMobile, setIsMobile] = React.useState(undefined)

  React.useEffect(() => {
    // matchMedia + a change listener keeps this in sync with window resizes
    // (including orientation changes), not just the initial render.
    const mql = window.matchMedia(`(max-width: ${MOBILE_BREAKPOINT - 1}px)`)
    const onChange = () => {
      setIsMobile(window.innerWidth < MOBILE_BREAKPOINT)
    }
    mql.addEventListener("change", onChange)
    setIsMobile(window.innerWidth < MOBILE_BREAKPOINT)
    return () => mql.removeEventListener("change", onChange)
  }, [])

  return !!isMobile
}
